"""Electromagnetism and circuit physics."""

from __future__ import annotations

import math
from typing import Optional

from funcpie.physics.constants import epsilon_0, mu_0


def coulombs_law(q1: float, q2: float, r: float, eps0: float = epsilon_0) -> float:
    """Coulomb's electrostatic force between two point charges: F = (1 / 4*pi*eps0) * (q1 * q2) / r^2."""
    if r <= 0:
        raise ValueError("Distance r must be strictly positive")
    k_e = 1.0 / (4.0 * math.pi * eps0)
    return k_e * (q1 * q2) / (r ** 2)


def electric_field_point_charge(q: float, r: float, eps0: float = epsilon_0) -> float:
    """Magnitude of electric field generated by a point charge: E = (1 / 4*pi*eps0) * q / r^2."""
    if r <= 0:
        raise ValueError("Distance r must be strictly positive")
    k_e = 1.0 / (4.0 * math.pi * eps0)
    return k_e * q / (r ** 2)


def electric_potential(q: float, r: float, eps0: float = epsilon_0) -> float:
    """Electric potential due to a point charge: V = (1 / 4*pi*eps0) * q / r."""
    if r <= 0:
        raise ValueError("Distance r must be strictly positive")
    k_e = 1.0 / (4.0 * math.pi * eps0)
    return k_e * q / r


def ohms_law_voltage(current: float, resistance: float) -> float:
    """Ohm's law voltage: V = I * R."""
    return current * resistance


def ohms_law_current(voltage: float, resistance: float) -> float:
    """Ohm's law current: I = V / R."""
    if resistance == 0:
        raise ZeroDivisionError("Resistance cannot be zero")
    return voltage / resistance


def ohms_law_resistance(voltage: float, current: float) -> float:
    """Ohm's law resistance: R = V / I."""
    if current == 0:
        raise ZeroDivisionError("Current cannot be zero")
    return voltage / current


def electric_power(
    voltage: Optional[float] = None,
    current: Optional[float] = None,
    resistance: Optional[float] = None,
) -> float:
    """Calculate electrical power in Watts given any two of (V, I, R)."""
    if voltage is not None and current is not None:
        return voltage * current
    elif voltage is not None and resistance is not None:
        if resistance == 0:
            raise ZeroDivisionError("Resistance cannot be zero")
        return (voltage ** 2) / resistance
    elif current is not None and resistance is not None:
        return (current ** 2) * resistance
    raise ValueError("Provide at least two parameters among (voltage, current, resistance)")


def resistors_series(*resistors: float) -> float:
    """Equivalent resistance for series connection: R_eq = sum(R_i)."""
    if not resistors:
        raise ValueError("At least one resistor value required")
    if any(r < 0 for r in resistors):
        raise ValueError("Resistances must be non-negative")
    return sum(resistors)


def resistors_parallel(*resistors: float) -> float:
    """Equivalent resistance for parallel connection: 1 / R_eq = sum(1 / R_i)."""
    if not resistors:
        raise ValueError("At least one resistor value required")
    if any(r <= 0 for r in resistors):
        raise ValueError("Resistances in parallel must be strictly positive")
    return 1.0 / sum(1.0 / r for r in resistors)


def capacitors_series(*capacitors: float) -> float:
    """Equivalent capacitance for series connection: 1 / C_eq = sum(1 / C_i)."""
    if not capacitors:
        raise ValueError("At least one capacitor value required")
    if any(c <= 0 for c in capacitors):
        raise ValueError("Capacitances in series must be strictly positive")
    return 1.0 / sum(1.0 / c for c in capacitors)


def capacitors_parallel(*capacitors: float) -> float:
    """Equivalent capacitance for parallel connection: C_eq = sum(C_i)."""
    if not capacitors:
        raise ValueError("At least one capacitor value required")
    if any(c < 0 for c in capacitors):
        raise ValueError("Capacitances must be non-negative")
    return sum(capacitors)


def capacitor_energy(capacitance: float, voltage: float) -> float:
    """Energy stored in an electric field of capacitor: E = 0.5 * C * V^2 (in Joules)."""
    if capacitance < 0:
        raise ValueError("Capacitance must be non-negative")
    return 0.5 * capacitance * (voltage ** 2)


def inductor_energy(inductance: float, current: float) -> float:
    """Energy stored in a magnetic field of inductor: E = 0.5 * L * I^2 (in Joules)."""
    if inductance < 0:
        raise ValueError("Inductance must be non-negative")
    return 0.5 * inductance * (current ** 2)


def rc_time_constant(resistance: float, capacitance: float) -> float:
    """Time constant of an RC circuit: tau = R * C."""
    if resistance < 0 or capacitance < 0:
        raise ValueError("Resistance and capacitance must be non-negative")
    return resistance * capacitance


def rc_charging_voltage(v_source: float, t: float, resistance: float, capacitance: float) -> float:
    """Voltage across charging capacitor at time t: V(t) = V_s * (1 - e^(-t / RC))."""
    tau = rc_time_constant(resistance, capacitance)
    if tau == 0:
        return v_source
    if t < 0:
        raise ValueError("time cannot be negative")
    return v_source * (1.0 - math.exp(-t / tau))


def rc_discharging_voltage(v_initial: float, t: float, resistance: float, capacitance: float) -> float:
    """Voltage across discharging capacitor at time t: V(t) = V_0 * e^(-t / RC)."""
    tau = rc_time_constant(resistance, capacitance)
    if tau == 0:
        return 0.0
    if t < 0:
        raise ValueError("time cannot be negative")
    return v_initial * math.exp(-t / tau)


def lorentz_force(charge: float, vel: float, b_field: float, angle_deg: float = 90.0) -> float:
    """Magnitude of magnetic Lorentz force on a moving charge: F = q * v * B * sin(theta)."""
    theta = math.radians(angle_deg)
    return abs(charge * vel * b_field * math.sin(theta))


def magnetic_field_wire(current: float, distance: float, mu0: float = mu_0) -> float:
    """Magnetic field at distance r from an infinitely long straight wire: B = mu0 * I / (2 * pi * r)."""
    if distance <= 0:
        raise ValueError("Distance must be strictly positive")
    return (mu0 * current) / (2.0 * math.pi * distance)


def solenoid_magnetic_field(turns_per_meter: float, current: float, mu0: float = mu_0) -> float:
    """Magnetic field inside an ideal solenoid: B = mu0 * n * I."""
    if turns_per_meter < 0:
        raise ValueError("Turns per meter must be non-negative")
    return mu0 * turns_per_meter * current
